def encode_geometry(g):
    """Named author dict -> (uint32 type, bytes parameters). triangles is flat indices."""
    spec = _validate(g)
    fields = spec["fields"]
    if "vertices" in fields:
        vertices, indices = g["vertices"], g.get("triangles", [])
        data = struct.pack("<II", len(vertices), len(indices)//3)
        data += b"".join(struct.pack("<3d", *v) for v in vertices)
        data += b"".join(struct.pack("<I", i) for i in indices)
    elif "halfspaces" in fields:
        data = struct.pack("<I", len(g["halfspaces"]))
        data += b"".join(struct.pack("<4d", *p) for p in g["halfspaces"])
    else:
        values = []
        for field in fields:
            values.extend(g[field.split("[")[0]] if "[" in field else [g[field]])
        data = struct.pack("<" + "d"*len(values), *values)
    return spec["type"], data

def decode_geometry(type_id, parameters):
    """Decode strict little-endian/binary64 bytes into the named author representation."""
    if type(type_id) is not int or type_id not in TYPE_NAMES:
        raise ValueError("unknown geometry type")
    name = TYPE_NAMES[type_id]
    data = memoryview(parameters)
    fields = REGISTRY[name]["fields"]
    g = {"type": name}
    if "vertices" in fields:
        if len(data) < 8:
            raise ValueError("truncated geometry")
        nv, nt = struct.unpack_from("<II", data)
        if len(data) != 8+24*nv+12*nt:
            raise ValueError("geometry counts do not match payload length")
        g["vertices"] = [list(struct.unpack_from("<3d", data, 8+i*24)) for i in range(nv)]
        if nt or name == "mesh":
            g["triangles"] = list(struct.unpack_from("<"+"I"*(nt*3), data, 8+24*nv))
    elif "halfspaces" in fields:
        if len(data) < 4:
            raise ValueError("truncated geometry")
        n, = struct.unpack_from("<I", data)
        if len(data) != 4+32*n:
            raise ValueError("halfspace count does not match payload length")
        g["halfspaces"] = [list(struct.unpack_from("<4d", data, 4+i*32)) for i in range(n)]
    else:
        offset = 0
        for field in fields:
            key = field.split("[")[0]
            count = int(field.split("[")[1][:-1]) if "[" in field else 1
            if offset + 8*count > len(data):
                raise ValueError("truncated geometry")
            values = struct.unpack_from("<"+"d"*count, data, offset)
            g[key] = list(values) if "[" in field else values[0]
            offset += 8*count
        if offset != len(data):
            raise ValueError("trailing geometry parameters")
    _validate(g)
    return g

